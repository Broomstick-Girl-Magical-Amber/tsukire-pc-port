// fetch.cpp - first run without the port: offers to download it from the GitHub release of this launcher.
//
// tsukihime_launcher.exe is published alone as a release asset. When the folder it runs from has no port (tools\,
// framework\), this asks the user and downloads the port from the same release, with no git:
//   curl.exe   tsukire-pc-port.zip.sha256, then tsukire-pc-port.zip          (both ship with Windows 10 1803+)
//   SHA-256    of the zip, computed here (bcrypt) and compared with the .sha256 asset; a mismatch unpacks nothing
//   tar.exe    -xkf zip -C <root>: -k never overwrites a file that already exists (a partial port is completed)
// The zip is made by tools\dev\pack_test_zip.ps1 -Release (only what the repo publishes: no game, no keys).
// launcher.ini port_tag records which tag was downloaded (for a future "update" button).
