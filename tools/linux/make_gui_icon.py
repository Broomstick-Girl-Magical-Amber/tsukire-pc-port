#!/usr/bin/env python3
"""make_gui_icon.py - Regenerates tools/linux/gui/icon_data.cpp: the 64x64 RGBA pixels of the port's own icon
(framework/games/tsukihime_common/tsukihime.ico, the icon of the game .exe and of the Windows launcher), which the
graphical launcher gives to its window with SDL_SetWindowIcon.

    python3 tools/linux/make_gui_icon.py          rewrite icon_data.cpp
    python3 tools/linux/make_gui_icon.py --check  exit 1 when icon_data.cpp is not up to date

Standard library only (the PNG inside the .ico is decoded by hand)."""
import struct
import sys
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
ICO = ROOT / "framework" / "games" / "tsukihime_common" / "tsukihime.ico"
OUT = ROOT / "tools" / "linux" / "gui" / "icon_data.cpp"
SIZE = 64


def ico_png(size):
    d = ICO.read_bytes()
    for i in range(struct.unpack("<H", d[4:6])[0]):
        w, h, _c, _r, _p, _b, n, off = struct.unpack("<BBBBHHII", d[6 + 16 * i:22 + 16 * i])
        if (w or 256) == size and d[off:off + 4] == b"\x89PNG":
            return d[off:off + n]
    raise SystemExit("no %dx%d PNG entry in %s" % (size, size, ICO))


def decode_png(data):
    pos, idat, ihdr = 8, b"", None
    while pos < len(data):
        n, typ = struct.unpack(">I4s", data[pos:pos + 8])
        body = data[pos + 8:pos + 8 + n]
        pos += 12 + n
        if typ == b"IHDR":
            ihdr = struct.unpack(">IIBBBBB", body)
        elif typ == b"IDAT":
            idat += body
    w, h, depth, ctype, _c, _f, inter = ihdr
    if depth != 8 or ctype not in (2, 6) or inter:
        raise SystemExit("only 8-bit RGB/RGBA PNG, not interlaced, is handled")
    bpp = 4 if ctype == 6 else 3
    raw, stride, prev, out = zlib.decompress(idat), w * bpp, bytearray(w * bpp), bytearray()
    for y in range(h):
        f = raw[y * (stride + 1)]
        line = bytearray(raw[y * (stride + 1) + 1:(y + 1) * (stride + 1)])
        for i in range(stride):
            a = line[i - bpp] if i >= bpp else 0
            b = prev[i]
            c = prev[i - bpp] if i >= bpp else 0
            if f == 1: line[i] = (line[i] + a) & 255
            elif f == 2: line[i] = (line[i] + b) & 255
            elif f == 3: line[i] = (line[i] + ((a + b) >> 1)) & 255
            elif f == 4:
                p = a + b - c
                pa, pb, pc = abs(p - a), abs(p - b), abs(p - c)
                line[i] = (line[i] + (a if pa <= pb and pa <= pc else b if pb <= pc else c)) & 255
        out += line
        prev = line
    if bpp == 3:
        rgba = bytearray()
        for i in range(0, len(out), 3):
            rgba += out[i:i + 3] + b"\xff"
        out = rgba
    return w, h, bytes(out)


def render():
    w, h, px = decode_png(ico_png(SIZE))
    lines = ["// icon_data.cpp - generated by tools/linux/make_gui_icon.py from the port's own tsukihime.ico. Do not edit.",
             "// (the extern declarations give the constants external linkage; launcher_gui.cpp declares them too)",
             "extern const int kIconW, kIconH;", "extern const unsigned char kIconRGBA[];", "",
             "const int kIconW = %d, kIconH = %d;" % (w, h), "const unsigned char kIconRGBA[] = {"]
    for i in range(0, len(px), 24):
        lines.append("    " + ",".join(str(b) for b in px[i:i + 24]) + ",")
    lines.append("};")
    return "\n".join(lines) + "\n"


def main():
    text = render()
    if "--check" in sys.argv:
        return 0 if OUT.exists() and OUT.read_text() == text else 1
    OUT.write_text(text)
    print("wrote %s" % OUT.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
