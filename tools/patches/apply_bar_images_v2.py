"""apply_bar_images.py - pictures for the bars at the sides of the picture on Android (AP_BAR_IMAGES), version 2.

On a phone wider than 16:9 the bars at the sides of the game's picture show its blurred edge (apply_android_present.py,
kFragmentExtend). With this patch, if <data root>/border exists, or <data root>/left_border and <data root>/right_border
do (png, jpg or jpeg; in that order of extension), the side bars show those pictures instead:
  - border is ONE picture for both sides: the game splits it in two halves, the left half is the picture of the left bar
    and the right half the one of the right bar (an odd width leaves out the middle column). It wins over left_border and
    right_border; if it is there but cannot be read, those two are tried;
  - each picture is scaled to the height of the screen and hangs from the edge of the game's picture, growing outwards:
    a screen only a little wider than 16:9 shows just the part of each picture next to the game, a wider one shows more;
  - the join with the game's picture is a clean cut;
  - where a bar is wider than its picture, and in the bars above and below (a screen taller than 16:9), the blurred edge
    of the existing shader is drawn.
Without a usable border, or both left_border and right_border, or with NX_BARS_STYLE=blur in config.txt, nothing changes:
the blurred bars. The pictures are the player's own files: nothing of them is in the repo. Up to 4096x4096 each (the whole
border too); the data root is data/<edition> (on the phone Tsukihime/data/<edition>). The file names are lower case.

Version 1 (2026-11-16) only read left_border and right_border. To update: python apply_bar_images.py --remove with the
version 1 file, replace it with this one, and apply.

Files (all under NX_EXTEND_BARS, which only Android defines):
  - runtime/src/nvn/nvn_present.cpp: kFragmentBars (kFragmentExtend plus the two pictures, in set 1 of a pipeline layout of
    its own: the set layout, the push constants and the pipelines of the rest of the pass are not touched), the loading of
    the files, their images (made once, copied in during the first frame), and the draw. The shader's GLSL is in the
    comment above the array. A failure anywhere keeps the blurred bars and logs one line ("nvn/vk: bar images: ...").
  - games/tsukihime_common/hle_carga.cpp: tsuki_decode_image, PNG and JPEG to RGBA8 with the libpng and libjpeg-turbo that
    AP_CARGA already links (weak in nvn_present.cpp: a build without it keeps the blurred bars).
  - tools/recomp_tsukihime.ps1: the two rows of $Markers, after the one of nvn_vk.cpp / AP_GPU_HANG (no other patcher
    anchors on it).
The runtime changes: for the phone, build_apk.ps1 and then build_android_pack.ps1 (+ pin_android_release.ps1) before
"Prepare for Android". Order: it edits the same file as apply_android_present.py but none of the text that one inserts, so
either can be removed first.
"""
